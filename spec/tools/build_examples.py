def build_vectors(out: Path) -> None:
    objs = [{"b": 2, "a": [1, "x", None], "c": {"z": True, "y": 1.5}}, {"spec": SPEC, "n": 10, "e": "é"}]
    rows = [verdict_row("v", i, "bodily_injury") for i in range(5)]
    hashes = [r["row_hash"] for r in rows]
    write_json(out / "hashing.json", {
        "jcs": [{"object": o, "jcs": rfc8785.dumps(o).decode(), "sha256": jcs_sha256(o)} for o in objs],
        "row_hash": [{"row": {k: r[k] for k in ROW_HASH_FIELDS}, "sha256": r["row_hash"]} for r in rows],
        "merkle": [{"leaves": hashes[:k], "root": merkle_root(hashes[:k])} for k in (0, 1, 2, 3, 5)],
    })
    # a 3-event audit chain: hash = sha256(JCS(event without hash)), prev_hash chains, genesis prev is 64 zeros
    events, prev = [], "0" * 64
    for seq, (actor, role, action, obj, outcome, rule) in enumerate([
        ("vik", "validator", "holdout.seal", {"type": "holdout", "id": HOLDOUT_ID}, "allowed", None),
        ("dana", "developer", "rebase.request", {"type": "rebase", "id": "13"}, "allowed", None),
        ("dana", "developer", "rebase.approve", {"type": "rebase", "id": "13"}, "denied", "SoD-02"),
    ], 1):
        ev = {"seq": seq, "ts": f"2026-11-01T1{seq}:00:00Z", "actor": actor, "role": role, "action": action,
              "object": obj, "outcome": outcome, "rule": rule, "payload": {"rows": 60} if seq == 1 else {},
              "prev_hash": prev}
        ev["hash"] = jcs_sha256(ev)
        prev = ev["hash"]
        events.append(ev)
    write_jsonl(out / "audit-chain.jsonl", events)
    key = test_key("receipt")
    write_json(out / "ed25519.json", {
        "note": "TEST KEY derived from a public string. Never use for a real receipt.",
        "seed_string": "roadbed fixture receipt key v0.1 - TEST ONLY",
        "public_raw_hex": raw_public(key).hex(), "keyid": sha256_hex(raw_public(key)),
        "message_utf8": "roadbed", "sig_b64": base64.b64encode(key.sign(b"roadbed")).decode(),
    })


