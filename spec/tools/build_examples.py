# ---------------------------------------------------------------- reference hashing (SPEC.md, hashing)


def sha256_hex(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def jcs_sha256(obj: Any) -> str:
    """sha256 of the RFC 8785 canonical JSON of obj."""
    return sha256_hex(rfc8785.dumps(obj))


ROW_HASH_FIELDS = ("interaction_id", "input_ref", "output", "verdict", "reason_code", "outcome", "ts")


def row_hash(row: dict[str, Any]) -> str:
    """sha256(JCS({interaction_id, input_ref, output, verdict, reason_code, outcome, ts})); absent fields are null."""
    return jcs_sha256({k: row.get(k) for k in ROW_HASH_FIELDS})


def merkle_root(row_hashes: list[str]) -> str:
    """RFC 6962 Merkle tree hash over the row hashes sorted ascending (duplicates kept).

    Leaf = sha256(0x00 || 32 raw digest bytes); node = sha256(0x01 || left || right);
    split at the largest power of two below n; the empty set hashes to sha256(b"").
    """
    leaves = [bytes.fromhex(h) for h in sorted(row_hashes)]

    def mth(d: list[bytes]) -> bytes:
        n = len(d)
        if n == 0:
            return hashlib.sha256(b"").digest()
        if n == 1:
            return hashlib.sha256(b"\x00" + d[0]).digest()
        k = 1
        while k * 2 < n:
            k *= 2
        return hashlib.sha256(b"\x01" + mth(d[:k]) + mth(d[k:])).digest()

    return mth(leaves).hex()


def test_key(name: str) -> Ed25519PrivateKey:
    return Ed25519PrivateKey.from_private_bytes(hashlib.sha256(f"roadbed fixture {name} key v0.1 - TEST ONLY".encode()).digest())


def raw_public(key: Ed25519PrivateKey) -> bytes:
    return key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def public_pem(key: Ed25519PrivateKey) -> bytes:
    return key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)


def sign(key: Ed25519PrivateKey, key_path: str, root: Path, signed: str, payload: str) -> dict[str, Any]:
    data = (root / signed).read_bytes()
    msg = rfc8785.dumps(json.loads(data)) if payload == "jcs" else data
    return {
        "alg": "ed25519",
        "keyid": sha256_hex(raw_public(key)),
        "key": key_path,
        "signed": signed,
        "payload": payload,
        "sig": base64.b64encode(key.sign(msg)).decode(),
    }


# ---------------------------------------------------------------- file helpers


def write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def ref(seed: str) -> str:
    return "sha256:" + sha256_hex(seed.encode())


def oid(seed: str) -> str:
    return sha256_hex(seed.encode())


def wrong(exp: dict[str, Any]) -> dict[str, Any]:
    return {**exp, "route": ROUTES[(ROUTES.index(exp["route"]) + 1) % 4]}


def verdict_row(prefix: str, i: int, line: str) -> dict[str, Any]:
    """A resolved verdict row (snapshot row shape)."""
    expected = {"route": ROUTES[i % 4], "severity": 1 + i % 5}
    fixed = i % 7 == 0
    row = {
        "interaction_id": f"int-{prefix}-{i:04d}",
        "input_ref": ref(f"{prefix}-input-{i}"),
        "output": wrong(expected) if fixed else dict(expected),
        "verdict": expected,
        "reason_code": "route_wrong" if fixed else None,
        "outcome": None,
        "ts": f"2026-10-{1 + i % 28:02d}T{8 + i % 9:02d}:{i % 60:02d}:00Z",
        "slices": {"line": line, "state": STATES[i % 3], "channel": CHANNELS[(i // 3) % 3]},
    }
    row["row_hash"] = row_hash(row)
    return row


