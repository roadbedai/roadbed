def write_snapshot(root: Path, sid: str, created: str, rows: list[dict[str, Any]], schema_sha: str, parent: str,
                   in_git: bool) -> dict[str, Any]:
    d = root / f"data/snapshots/{sid.removeprefix('S-')}"
    part_bytes = "".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) + "\n" for r in rows).encode()
    part = {"oid": sha256_hex(part_bytes), "rows": len(rows), "size": len(part_bytes)}
    if in_git:
        d.mkdir(parents=True, exist_ok=True)
        (d / "part-0000.jsonl").write_bytes(part_bytes)
        part["path"] = f"data/snapshots/{sid.removeprefix('S-')}/part-0000.jsonl"
        (d / "SYNTHETIC.md").write_text(SYNTHETIC_MD, encoding="utf-8")
    man = {
        "spec": SPEC, "id": sid, "created_at": created, "rows": len(rows), "schema_sha256": schema_sha,
        "merkle_root": merkle_root([r["row_hash"] for r in rows]), "parts": [part], "label_rules": "label_rules@v1",
        "pseudonymisation": {"profile": "insurer-default@v1", "hmac_key_id": "acme-hmac-2026-10"},
        "parent": parent, "synthetic": True,
    }
    write_json(d / "MANIFEST.json", man)
    return man


